/*
 * Ported Triforce% cutscenes - every CS array vendored under scenes/ and actors/ pulled
 * into the TrifoolPercent module as compilable CutsceneData[]. Each array is namespaced
 * `gTrifool<Original>Cs` so no symbol clashes a vanilla scene's CS data. These are the
 * raw scripts; triggers and placeholder text registration land per-phase elsewhere.
 *
 * (c) The Triforce% team, used with credit under upstream/TRIFORCE-PERCENT-LICENSE.txt.
 * Transformations from the originals, kept minimal:
 *   - Each `s32 Foo[]` becomes `CutsceneData gTrifoolFooCs[]`.
 *   - File-local `#include`s dropped; module header carries externs.
 *   - FOV view-angle fields left as raw float bit patterns (e.g. 0x42700000 = 60.0f);
 *     readability pass can convert them later.
 *   - Custom BGM slots (0x72 PowerOfTheGoddesses, 0x73-0x75 HereTogether) left as-is;
 *     they play silence until AudioCollection registers the sequences. Vanilla BGM
 *     slots (desert 0x3F, gerudoway 0x3D, horse race 0x1B, song learned 0x18,
 *     staff roll 0x76) resolve on this build already.
 *   - CS_TERMINATOR cases preserved as-is. Any case Triforce% re-aimed in
 *     statics/scene.c (81, 82, 84-93 flyover chain) will not reach a Triforce%
 *     entrance in vanilla - callers watch csCtx.frames in C and reroute via
 *     nextEntranceIndex (same shape as LeaveTriforceRoomAtCutsceneEnd).
 */

